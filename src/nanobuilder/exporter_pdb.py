"""PDB export (structure + bonds), readable by AMBER (tleap), GROMACS (pdb2gmx /
editconf) and most visualization tools.

Layout:
- ``CRYST1`` carries the cell, so periodic slabs keep their box.
- Substrate atoms are ``HETATM`` records in chain A, one residue per atom with
  the element as residue name (``AU``, ``NA``, ...), the usual convention for
  metal and ionic atoms in AMBER and GROMACS workflows.
- Each ligand is one residue ``LIG`` in chain B; atom names are element +
  running number within the ligand (``S1``, ``C1``, ``C2``, ``H1`` ...).
- ``CONECT`` records list every ligand bond and every covalent surface bond.
- Molecules are written whole (never split across the periodic boundary).

PDB fixed columns limit atom serials to 99999 and residue numbers to 9999.
Above 99999 atoms, serials wrap and CONECT records are omitted, because they
could no longer identify atoms uniquely; the export report says so.
"""

from __future__ import annotations

import hashlib
from collections import defaultdict
from pathlib import Path

import numpy as np
from ase.geometry import cell_to_cellpar

from . import __version__
from .schema import AssemblyModel, ExportReport

MAX_SERIAL = 99999
LIGAND_RESNAME = "LIG"


def _atom_names(assembly: AssemblyModel) -> list:
    """Unique-within-residue atom names: substrate = element, ligand = element + count."""
    names, counters = [], defaultdict(int)
    current = None
    for element, mol, comp in zip(assembly.elements, assembly.molecule_id, assembly.component):
        if comp == "substrate":
            names.append(element.upper()[:4])
            continue
        if mol != current:
            current, counters = mol, defaultdict(int)
        counters[element] += 1
        names.append(f"{element.upper()}{counters[element]}"[:4])
    return names


def _format_name(name: str, element: str) -> str:
    # PDB convention: one-letter elements start in column 14, two-letter in column 13.
    return f" {name:<3}" if len(element) == 1 and len(name) < 4 else f"{name:<4}"


def pdb_text(assembly: AssemblyModel) -> tuple:
    """Return (text, warnings)."""
    warnings = []
    n = assembly.n_atoms
    wrap_serials = n > MAX_SERIAL
    if wrap_serials:
        warnings.append(f"{n} atoms exceed the PDB limit of {MAX_SERIAL}: atom serials wrap and "
                        "CONECT records are omitted; use the LAMMPS or GSD file for bonds")
    lines = [f"REMARK   1 Generated by nanobuilder {__version__}: structure and bonds only",
             "REMARK   1 No force field, no charges",
             "REMARK   1 Substrate: chain A; ligands: chain B, residue " + LIGAND_RESNAME,
             "REMARK   1 Metal substrates: one residue per atom; carbon substrates: GRA",
             "REMARK   1 per framework carbon (with its edge H), OH/EPX/ETH/CBO/CBX per group"]
    a, b, c, alpha, beta, gamma = cell_to_cellpar(np.asarray(assembly.cell_A))
    lines.append(f"CRYST1{a:9.3f}{b:9.3f}{c:9.3f}{alpha:7.2f}{beta:7.2f}{gamma:7.2f} P 1           1")

    names = _atom_names(assembly)
    covalent = assembly.residue_names is not None
    if covalent:  # carbon substrates: residues per framework carbon / functional group
        names = [assembly.atom_names[k][:4] if assembly.component[k] == "substrate" else names[k]
                 for k in range(n)]
    serials = [(k % MAX_SERIAL) + 1 if wrap_serials else k + 1 for k in range(n)]
    resseq, last_mol, sub_res, lig_res, last_sub = [], None, 0, 0, None
    for k, (comp, mol) in enumerate(zip(assembly.component, assembly.molecule_id)):
        if comp == "substrate":
            if covalent:
                if assembly.residue_ids[k] != last_sub:
                    sub_res += 1
                    last_sub = assembly.residue_ids[k]
            else:
                sub_res += 1
            resseq.append(sub_res)
        else:
            if mol != last_mol:
                lig_res += 1
                last_mol = mol
            resseq.append(lig_res)
    if max(resseq, default=0) > 9999:
        warnings.append("More than 9999 residues in a chain: residue numbers wrap after 9999")

    prev_chain = None
    for k in range(n):
        element = assembly.elements[k]
        sub = assembly.component[k] == "substrate"
        chain = "A" if sub else "B"
        if prev_chain is not None and chain != prev_chain:
            lines.append("TER")
        prev_chain = chain
        record = "HETATM"
        if sub:
            resname = assembly.residue_names[k][:3] if covalent else element.upper()[:3]
        else:
            resname = LIGAND_RESNAME
        x, y, z = assembly.positions_A[k]
        lines.append(f"{record:<6}{serials[k]:>5} {_format_name(names[k], element)} {resname:>3} "
                     f"{chain}{(resseq[k] - 1) % 9999 + 1:>4}    {x:8.3f}{y:8.3f}{z:8.3f}"
                     f"{1.0:6.2f}{0.0:6.2f}          {element.upper():>2}")
    if n:
        lines.append("TER")

    if not wrap_serials:
        partners = defaultdict(list)
        for i, j, *_ in assembly.bond_list:
            partners[i].append(j)
            partners[j].append(i)
        for i in sorted(partners):
            js = sorted(partners[i])
            for start in range(0, len(js), 4):
                chunk = "".join(f"{serials[j]:>5}" for j in js[start:start + 4])
                lines.append(f"CONECT{serials[i]:>5}{chunk}")
    lines.append("END")
    return "\n".join(lines) + "\n", warnings


def export_pdb(assembly: AssemblyModel, path) -> ExportReport:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text, warnings = pdb_text(assembly)
    path.write_text(text, encoding="ascii")
    problems = check_round_trip(assembly, path)
    return ExportReport(
        path=str(path), format="pdb", sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        n_atoms=assembly.n_atoms, n_bonds=len(assembly.bond_list),
        round_trip_passed=not problems,
        warnings=problems + warnings + [
            "PDB atom and residue names are structural labels; AMBER/GROMACS force-field "
            "residue templates must be provided by the user"])


def read_pdb(path) -> dict:
    """Minimal fixed-column parser for what this exporter writes (round-trip checks)."""
    atoms, conect, cryst = [], defaultdict(set), None
    for line in Path(path).read_text(encoding="ascii").splitlines():
        rec = line[:6].strip()
        if rec in ("ATOM", "HETATM"):
            atoms.append({"serial": int(line[6:11]), "name": line[12:16].strip(),
                          "resname": line[17:20].strip(), "chain": line[21],
                          "resseq": int(line[22:26]),
                          "xyz": (float(line[30:38]), float(line[38:46]), float(line[46:54])),
                          "element": line[76:78].strip()})
        elif rec == "CONECT":
            fields = [int(line[k:k + 5]) for k in range(6, len(line.rstrip()), 5)]
            conect[fields[0]].update(fields[1:])
        elif rec == "CRYST1":
            cryst = [float(line[6:15]), float(line[15:24]), float(line[24:33]),
                     float(line[33:40]), float(line[40:47]), float(line[47:54])]
    return {"atoms": atoms, "conect": conect, "cryst1": cryst}



def check_round_trip(assembly: AssemblyModel, path) -> list:
    problems = []
    data = read_pdb(path)
    atoms = data["atoms"]
    if len(atoms) != assembly.n_atoms:
        return [f"Atom count {len(atoms)} != {assembly.n_atoms}"]
    elements = [a["element"].capitalize() for a in atoms]
    if elements != [e.capitalize() for e in assembly.elements]:
        problems.append("Elements differ")
    xyz = np.array([a["xyz"] for a in atoms])
    if not np.allclose(xyz, assembly.positions_A, atol=1.5e-3):
        problems.append("Coordinates differ beyond PDB precision")
    cellpar = cell_to_cellpar(np.asarray(assembly.cell_A))
    if data["cryst1"] is None or not np.allclose(data["cryst1"], cellpar, atol=2e-2):
        problems.append("CRYST1 does not match the cell")
    if assembly.n_atoms <= MAX_SERIAL:
        written = {tuple(sorted((i, j))) for i, js in data["conect"].items() for j in js}
        expected = {tuple(sorted((i + 1, j + 1))) for i, j, *_ in assembly.bond_list}
        if written != expected:
            problems.append(f"CONECT bonds differ ({len(written)} written, {len(expected)} expected)")
    return problems
