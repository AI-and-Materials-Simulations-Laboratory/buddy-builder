"""Tripos MOL2 export with suggested GAFF2 atom types (AMBER-oriented).

Follows the layout of the AMBER graphene-oxide dataset (Fedai et al., Data 11,
18, 2026): GAFF-style types in the atom-type column, residues per functional
group (GRA basal carbons, OH, EPX, plus ETH, CBO, CBX for HierGO's aged groups)
or one residue ``GRO`` for the whole substrate (recommended there when GO is
combined with biomolecules), bond orders (1, 2, ar, am) and a rebuilt
SUBSTRUCTURE section. Charges are written as 0.0000 with NO_CHARGES: the
dataset's GO charges (Stauffer et al. 2014) and ligand charges (e.g.
antechamber -c bcc) must be assigned by the user.

Periodic models get a CRYSIN record; bonds that cross the periodic boundary
are written as ordinary bonds (tleap cannot represent them; see README_mol2).
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np
from ase.geometry import cell_to_cellpar

from . import __version__
from .schema import AssemblyModel, ExportReport

BOND_CODE = {1.0: "1", 1.5: "ar", 2.0: "2", 3.0: "3"}


def _residues(assembly: AssemblyModel, scheme: str):
    """(names, ids) per atom; substrate residues follow ``scheme``; ligands are LIG."""
    n = assembly.n_atoms
    names, ids = [], []
    if assembly.residue_names is not None:
        src_names, src_ids = list(assembly.residue_names), list(assembly.residue_ids)
    else:  # metal/crystal substrates: one residue per substrate atom, LIG per ligand
        src_names, src_ids, last, r = [], [], None, 0
        for k in range(n):
            if assembly.component[k] == "substrate":
                r += 1
                src_names.append(assembly.elements[k].upper()[:3])
            else:
                mol = int(assembly.molecule_id[k])
                if mol != last:
                    r += 1
                    last = mol
                src_names.append("LIG")
            src_ids.append(r)
    if scheme == "single" and assembly.residue_names is not None:
        r, last = 1, None
        for k in range(n):
            if assembly.component[k] == "substrate":
                names.append("GRO")
                ids.append(1)
            else:
                if src_ids[k] != last:
                    r += 1
                    last = src_ids[k]
                names.append(src_names[k])
                ids.append(r)
        return names, ids
    # renumber 1..R in order of appearance
    remap, out = {}, []
    for rid in src_ids:
        if rid not in remap:
            remap[rid] = len(remap) + 1
        out.append(remap[rid])
    return src_names, out


def _atom_names(elements, ids):
    out, counters, last = [], {}, None
    for e, r in zip(elements, ids):
        if r != last:
            counters, last = {}, r
        counters[e] = counters.get(e, 0) + 1
        out.append(f"{e}{counters[e]}")
    return out


def _bond_code(assembly, k, types):
    i, j = assembly.bond_list[k][:2]
    order = float(assembly.bond_orders[k]) if assembly.bond_orders else 1.0
    code = BOND_CODE.get(order, "1")
    if code == "1" and types is not None:  # amide C-N
        pair = {types[i], types[j]}
        if pair == {"c", "n"}:
            return "am"
    return code


def mol2_text(assembly: AssemblyModel, residue_scheme: str = "groups", title: str = "") -> tuple:
    warnings = []
    names_res, ids = _residues(assembly, residue_scheme)
    atom_names = _atom_names(assembly.elements, ids)
    types = (assembly.suggested_types or {}).get("gaff2")
    if types is None:
        types = list(assembly.elements)
        warnings.append("No suggested GAFF2 types: element symbols written as atom types")
    n_res = max(ids) if ids else 0
    lines = ["@<TRIPOS>MOLECULE", title or "nanobuilder",
             f"{assembly.n_atoms} {len(assembly.bond_list)} {n_res} 0 0", "SMALL", "NO_CHARGES",
             f"Generated by nanobuilder {__version__}; GAFF2-style types are suggestions, "
             "charges unassigned", "", "@<TRIPOS>ATOM"]
    pos = np.asarray(assembly.positions_A)
    for k in range(assembly.n_atoms):
        x, y, z = pos[k]
        lines.append(f"{k + 1:>7d} {atom_names[k]:<8s} {x:>10.4f} {y:>10.4f} {z:>10.4f} "
                     f"{types[k]:<6s} {ids[k]:>6d} {names_res[k]:<6s} {0.0:>9.4f}")
    lines.append("@<TRIPOS>BOND")
    for k, (i, j, *_) in enumerate(assembly.bond_list):
        lines.append(f"{k + 1:>7d} {i + 1:>7d} {j + 1:>7d} {_bond_code(assembly, k, types)}")
    lines.append("@<TRIPOS>SUBSTRUCTURE")
    first = {}
    for k, r in enumerate(ids):
        first.setdefault(r, (k + 1, names_res[k], assembly.component[k]))
    for r in sorted(first):
        root, name, comp = first[r]
        chain = "A" if comp == "substrate" else "B"
        lines.append(f"{r:>7d} {name:<6s} {root:>7d} RESIDUE 1 {chain} {name:<6s} 0")
    if any(assembly.pbc):
        a, b, c, al, be, ga = cell_to_cellpar(np.asarray(assembly.cell_A))
        lines += ["@<TRIPOS>CRYSIN", f"{a:.4f} {b:.4f} {c:.4f} {al:.2f} {be:.2f} {ga:.2f} 1 1"]
        if assembly.n_substrate and assembly.residue_names is not None:
            warnings.append("Periodic carbon framework: some bonds cross the cell boundary; tleap "
                            "cannot represent them (build a finite flake or tube for AMBER)")
    return "\n".join(lines) + "\n", warnings


def read_mol2(path) -> dict:
    atoms, bonds, section = [], [], None
    for line in Path(path).read_text(encoding="ascii").splitlines():
        if line.startswith("@<TRIPOS>"):
            section = line[9:].strip()
            continue
        parts = line.split()
        if not parts:
            continue
        if section == "ATOM":
            atoms.append({"id": int(parts[0]), "name": parts[1],
                          "xyz": tuple(float(v) for v in parts[2:5]), "type": parts[5],
                          "resid": int(parts[6]), "resname": parts[7]})
        elif section == "BOND":
            bonds.append((int(parts[1]), int(parts[2]), parts[3]))
    return {"atoms": atoms, "bonds": bonds}


def check_round_trip(assembly: AssemblyModel, path) -> list:
    data = read_mol2(path)
    problems = []
    if len(data["atoms"]) != assembly.n_atoms:
        return [f"Atom count {len(data['atoms'])} != {assembly.n_atoms}"]
    xyz = np.array([a["xyz"] for a in data["atoms"]])
    if not np.allclose(xyz, assembly.positions_A, atol=2e-4):
        problems.append("Coordinates differ")
    written = {tuple(sorted((i, j))) for i, j, _ in data["bonds"]}
    expected = {tuple(sorted((i + 1, j + 1))) for i, j, *_ in assembly.bond_list}
    if written != expected:
        problems.append(f"Bonds differ ({len(written)} written, {len(expected)} expected)")
    return problems


def export_mol2(assembly: AssemblyModel, path, residue_scheme: str = "groups",
                title: str = "") -> ExportReport:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text, warnings = mol2_text(assembly, residue_scheme, title)
    path.write_text(text, encoding="ascii", newline="\n")
    problems = check_round_trip(assembly, path)
    return ExportReport(
        path=str(path), format="mol2", sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        n_atoms=assembly.n_atoms, n_bonds=len(assembly.bond_list), round_trip_passed=not problems,
        warnings=problems + warnings + ["MOL2 atom types are suggested GAFF2 names (ligand types "
                                        "provisional); charges are 0.0000 placeholders"])


